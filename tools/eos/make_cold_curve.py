#!/usr/bin/env python3
"""Write data/eos/cold_curve.dat: the T = 0 energy density eps_c(rho) of the two-phase model.

Uses the reference prototype (quintic spline between 4.2 and 10.5 rho_s, build(0.0, 4.2*rhos, 10.5*rhos),
evaluated with f_all).  The prototype works in MeV and fm; the conversion to GeV is done here only.

Table rows:   rho [fm^-3]   eps_c [GeV/fm^3]   mu_c = d eps_c / d rho [GeV]
Grid: uniform, 0 ... 16 rho_s, step 0.005 rho_s (rho_s = 0.153 fm^-3).
At rho = 0 the row is eps_c = 0 and mu_c = m_N = 0.940 GeV, the analytic limit of the hadronic branch
(mu_H = mu_0 + dw/drho with mu_0 -> m_N and dw -> 0 for rho -> 0).
"""
import hashlib, json, os, sys

here = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, here)
import eos_reference_prototype as proto  # noqa: E402

STEP_RHOS = 0.005
RHO_MAX_RHOS = 16.0
MATCH_H, MATCH_Q = 4.2, 10.5


def main(out_path):
    rhos = proto.rhos
    ref_path = os.path.join(here, "eos_reference_values.json")
    raw = open(ref_path, "rb").read()
    sha = hashlib.sha256(raw).hexdigest()
    ref = json.loads(raw)["T0_spline"]

    S = proto.build(0.0, MATCH_H * rhos, MATCH_Q * rhos)
    R = proto.analyse(S)
    # consistency with the stored reference numbers
    for k in ("rho1", "rho2", "rhoA", "rhoB", "mu_coex", "p_coex"):
        assert abs(R[k] - ref[k]) < 1e-6 * max(1.0, abs(ref[k])), (k, R[k], ref[k])

    n = int(round(RHO_MAX_RHOS / STEP_RHOS))
    d_rho = STEP_RHOS * rhos
    rows = []
    for i in range(n + 1):
        rho = i * d_rho
        if i == 0:
            e, mu = 0.0, proto.mN
        else:
            e, mu = proto.f_all(S, rho, 0), proto.f_all(S, rho, 1)
        rows.append((rho, e / 1000.0, mu / 1000.0))

    hdr = [
        "# Cold (T = 0) energy density of the two-phase equation of state, rest mass included.",
        "# Generated by tools/eos/make_cold_curve.py from tools/eos/eos_reference_prototype.py; do not edit.",
        "# Columns: rho [fm^-3]   eps_c [GeV/fm^3]   mu_c = d eps_c/d rho [GeV]",
        "# Units: GeV, fm. At rho = 0: eps_c = 0, mu_c = m_N = 0.940 GeV (analytic limit of the hadronic branch).",
        "# Key = value lines below are read by the C++ loader.",
        "# rho_s_fm3 = %r" % rhos,
        "# match_hadron_rho_s = %r" % MATCH_H,
        "# match_plasma_rho_s = %r" % MATCH_Q,
        "# rho_1_fm3 = %r" % (R["rho1"] * rhos),
        "# rho_2_fm3 = %r" % (R["rho2"] * rhos),
        "# mu_coex_GeV = %r" % (R["mu_coex"] / 1000.0),
        "# p_coex_GeV_fm3 = %r" % (R["p_coex"] / 1000.0),
        "# d_rho_fm3 = %r" % d_rho,
        "# n_rows = %d" % len(rows),
        "# eos_reference_values_json_sha256 = %s" % sha,
    ]
    os.makedirs(os.path.dirname(out_path), exist_ok=True)
    with open(out_path, "w") as f:
        f.write("\n".join(hdr) + "\n")
        for r in rows:
            f.write("%.17e %.17e %.17e\n" % r)
    print("wrote", out_path, len(rows), "rows; rho1,rho2 [rho_s] =", R["rho1"], R["rho2"], "sha256", sha[:12])


if __name__ == "__main__":
    root = os.path.abspath(os.path.join(here, "..", ".."))
    main(sys.argv[1] if len(sys.argv) > 1 else os.path.join(root, "data", "eos", "cold_curve.dat"))
